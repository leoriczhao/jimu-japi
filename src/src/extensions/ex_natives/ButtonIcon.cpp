// ButtonIcon.cpp - YDWE EXDclareButtonIcon / EXBlendButtonIcon.
//
// Historical names are preserved exactly (including YDWE's "Dclare" typo).
// The image work is real:
//   * source BLP is read through Storm.dll's documented file APIs (no IAT
//     interception, no SFileLoadFile hook);
//   * YDWE's disabled/blend pixel algorithms run in image/button_icon.cpp;
//   * the result is encoded as a real BLP1 palette file and written below
//     <map directory>\japi-button-icons\<map-relative path>.
//
// What is deliberately NOT done: the game's command-card loader asks MPQ for
// ReplaceableTextures\CommandButtonsDisabled\DIS*.blp. Without intercepting
// that request there is no way to serve the generated bytes to the running
// session. The generated tree is a build input: copy it into the map's
// -BaseMap source directory (and (listfile)) and repack. The next session loads
// the disabled icon natively from the map archive. This limitation is
// documented in docs/guide/YDWE-COMPAT.md.
