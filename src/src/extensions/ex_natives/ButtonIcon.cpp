	uint32_t EXDclareButtonIcon_handler(const uint32_t* args, size_t)
	{
		const std::string path = jstring_to_utf8(static_cast<jass::jstring_t>(args[0]));
		if (path.empty()) {
			DBG_LOG("[ButtonIcon] EXDclareButtonIcon: empty path");
			return 0;
		}
		try {
			std::string written;
			std::string error;
			if (!declare_button_icon(path, &written, &error)) {
				DBG_LOG("[ButtonIcon] EXDclareButtonIcon(%s) failed: %s",
					path.c_str(), error.c_str());
				return 0;
			}
			DBG_LOG("[ButtonIcon] EXDclareButtonIcon(%s) wrote %s",
				path.c_str(), written.c_str());
		} catch (const std::exception& error) {
			DBG_LOG("[ButtonIcon] EXDclareButtonIcon(%s) exception: %s",
				path.c_str(), error.what());
		}
		return 0;
	}

	uint32_t EXBlendButtonIcon_handler(const uint32_t* args, size_t)
	{
		const std::string input_a = jstring_to_utf8(static_cast<jass::jstring_t>(args[0]));
		const std::string input_b = jstring_to_utf8(static_cast<jass::jstring_t>(args[1]));
		const std::string output = jstring_to_utf8(static_cast<jass::jstring_t>(args[2]));
		if (input_a.empty() || input_b.empty() || output.empty()) {
			DBG_LOG("[ButtonIcon] EXBlendButtonIcon: empty path argument");
			return 0;
		}
		try {
			std::string written;
			std::string error;
			if (!blend_button_icons(input_a, input_b, output, &written, &error)) {
				DBG_LOG("[ButtonIcon] EXBlendButtonIcon(%s, %s, %s) failed: %s",
					input_a.c_str(), input_b.c_str(), output.c_str(), error.c_str());
				return 0;
			}
			DBG_LOG("[ButtonIcon] EXBlendButtonIcon wrote %s", written.c_str());
		} catch (const std::exception& error) {
			DBG_LOG("[ButtonIcon] EXBlendButtonIcon exception: %s", error.what());
			return 0;
		}
		return 1;
	}

