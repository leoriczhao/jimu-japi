// tests/conformance/gen-manifest.mjs — regenerate manifest.lua from the engine registry.
//
// The conformance map must not hardcode what the engine claims to implement: it
// derives it from src/ so that a new handler shows up as a new (failing) row the
// moment it is registered, and a removed one disappears.
//
//   node tests/conformance/gen-manifest.mjs
//
// Sources:
//   * register_cpp_handler("Name", "(spec)")  -> callable from Lua as jass.japi.Name
//   * jass::japi_add(..., "Name", "(spec)")   -> declared JASS native (not registered at
//                                                runtime today, see plan P3-E1)
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..', '..');
const srcRoot = path.join(root, 'src', 'src');

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p, out);
    else if (/\.(cpp|h)$/i.test(entry.name)) out.push(p);
  }
  return out;
}

const files = walk(srcRoot);
const bridge = new Map();
const declared = new Map();

for (const file of files) {
  const text = fs.readFileSync(file, 'utf8');
  // Drop line comments so commented-out registrations stay out of the table.
  const code = text.replace(/\/\/[^\n]*/g, '');
  for (const m of code.matchAll(/register_cpp_handler\s*\(\s*"([^"]+)"\s*,\s*"([^"]+)"/g)) {
    bridge.set(m[1], m[2]);
  }
  for (const m of code.matchAll(/japi_add\s*\(\s*\(uintptr_t\)\s*\w+\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"/g)) {
    declared.set(m[1], m[2]);
  }
}

const rows = [...bridge.entries()].sort((a, b) => a[0].localeCompare(b[0]));
const decl = [...declared.entries()].sort((a, b) => a[0].localeCompare(b[0]));

const quote = (s) => "'" + s.replace(/'/g, "\\'") + "'";
const lines = [];
lines.push('-- GENERATED by tests/conformance/gen-manifest.mjs — do not edit by hand.');
lines.push('-- Snapshot of what the engine registry claims: bridge handlers callable from Lua');
lines.push('-- via jass.japi, and natives declared with jass::japi_add but not registered yet.');
lines.push('local M = {}');
lines.push('');
lines.push('M.bridge = {');
for (const [name, spec] of rows) lines.push('    { name = ' + quote(name) + ', spec = ' + quote(spec) + ' },');
lines.push('}');
lines.push('');
lines.push('M.declared = {');
for (const [name, spec] of decl) lines.push('    { name = ' + quote(name) + ', spec = ' + quote(spec) + ' },');
lines.push('}');
lines.push('');
lines.push('return M');
fs.writeFileSync(path.join(root, 'tests', 'conformance', 'manifest.lua'), lines.join('\n') + '\n', 'utf8');
console.log('manifest.lua: bridge=' + rows.length + ' declared=' + decl.length);
